"""Shared plumbing for experiment runners.

PLAN.md's rule: every number that reaches the paper is generated by a script
into results/<EID>.tex and \\input into the document.  Nothing is hand-typed.
Each results file carries a provenance header naming the experiment, the git
revision, the config hash and -- critically -- whether the inputs were MEASURED
or SYNTHETIC.
"""
from __future__ import annotations
import hashlib, json, os, subprocess, sys, time
import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RESULTS = os.path.join(ROOT, "results")
sys.path.insert(0, os.path.join(ROOT, "src"))
os.makedirs(RESULTS, exist_ok=True)


def git_rev():
    try:
        return subprocess.check_output(["git", "rev-parse", "--short", "HEAD"],
                                       cwd=ROOT, stderr=subprocess.DEVNULL
                                       ).decode().strip()
    except Exception:
        return "no-git"


def cfg_hash(cfg: dict) -> str:
    return hashlib.sha256(json.dumps(cfg, sort_keys=True, default=str)
                          .encode()).hexdigest()[:12]


class Result:
    def __init__(self, eid, title, cfg, provenance="SYNTHETIC"):
        self.eid, self.title, self.cfg = eid, title, cfg
        self.provenance = provenance
        self.rows, self.scalars, self.t0 = [], {}, time.time()

    def scalar(self, key, value, fmt="{:.4f}"):
        self.scalars[key] = (value, fmt)
        return value

    def row(self, **kw):
        self.rows.append(kw)

    def _header(self):
        return (f"%% GENERATED by experiments/{self.eid}.py -- do not edit\n"
                f"%% {self.title}\n"
                f"%% provenance : {self.provenance}\n"
                f"%% git        : {git_rev()}\n"
                f"%% config     : {cfg_hash(self.cfg)}\n"
                f"%% generated  : {time.strftime('%Y-%m-%d %H:%M:%S')}\n"
                f"%% runtime    : {time.time() - self.t0:.1f}s\n")

    def write(self, tex_body: str = ""):
        with open(os.path.join(RESULTS, f"{self.eid}.tex"), "w") as f:
            f.write(self._header())
            for k, (v, fmt) in self.scalars.items():
                f.write(f"\\newcommand{{\\{self.eid}{k}}}{{"
                        + (fmt.format(v) if isinstance(v, (int, float, np.floating))
                           else str(v)) + "}\n")
            if tex_body:
                f.write("\n" + tex_body + "\n")
        payload = {"eid": self.eid, "title": self.title,
                   "provenance": self.provenance, "git": git_rev(),
                   "config": self.cfg, "cfg_hash": cfg_hash(self.cfg),
                   "scalars": {k: (float(v) if isinstance(v, (int, float, np.floating))
                                   else v) for k, (v, _) in self.scalars.items()},
                   "rows": self.rows,
                   "runtime_s": round(time.time() - self.t0, 1)}
        with open(os.path.join(RESULTS, f"{self.eid}.json"), "w") as f:
            json.dump(payload, f, indent=2, default=float)
        print(f"\n-> results/{self.eid}.tex  and  results/{self.eid}.json")


def banner(eid, title):
    print("=" * 74)
    print(f"{eid}  {title}")
    print("=" * 74)
